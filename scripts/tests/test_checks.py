"""Tests for the rule checks: check-refs.py and check-attribution.py."""

import importlib.util
import shutil
import subprocess
from pathlib import Path
from types import ModuleType

import pytest


def load(name: str) -> ModuleType:
    path = Path(__file__).resolve().parent.parent / f"{name}.py"
    spec = importlib.util.spec_from_file_location(name.replace("-", "_"), path)
    assert spec
    assert spec.loader
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


refs = load("check-refs")
attribution = load("check-attribution")
RULE = refs.LISTS["AGENTS.md rule"][3]
MISTAKE = refs.LISTS["lesson"][3]
DOCS = refs.LISTS["pull-request skill"][3] + refs.LISTS["standards"][3]
# CI's python job runs in uv's slim image, which has no git; the rules workflow runs the real check.
needs_git = pytest.mark.skipif(
    shutil.which("git") is None, reason="no git here; rules.yml runs check-refs"
)


def test_expand_reads_lists_and_ranges():
    assert refs.expand("8 to 10") == [8, 9, 10]
    assert refs.expand("17–18") == [17, 18]
    assert refs.expand("16 and 25") == [16, 25]
    assert refs.expand("11, 12 and 13") == [11, 12, 13]
    assert refs.expand("8-10") == [8, 9, 10]


def test_references_finds_rules_and_lessons():
    text = "see rules 25 and 26\nlessons 40 and lessons 9 to 10\nnothing here"
    assert [(line, n) for line, n, _ in refs.references("README.md", text, RULE)] == [
        (1, 25),
        (1, 26),
    ]
    assert [n for _, n, _ in refs.references("README.md", text, MISTAKE)] == [40, 9, 10]


def test_references_finds_skills_and_docs_cited_as_links_and_paths():
    text = (
        "as the [`pull-request`](.claude/skills/pull-request/SKILL.md) skill 1 says; "
        "`docs/standards.md` 15"
    )
    assert [n for _, n, _ in refs.references("AGENTS.md", text, DOCS)] == [1, 15]


def test_numbering_needs_order_only_where_the_list_has_it():
    assert refs.numbering(["a.md"], [1, 2, 4], in_order=True) != []
    assert refs.numbering(["a.md"], [1, 2, 29, 3], in_order=False) == []
    assert refs.numbering(["a.md"], [1, 2, 2], in_order=False) == ["a.md: 2 is used more than once"]


def test_bare_numbers_count_only_inside_agents_md():
    assert refs.references("README.md", "colours (25–29)", RULE) == []
    assert [n for _, n, _ in refs.references("AGENTS.md", "Plan (G1) (14)", RULE)] == [14]


def test_moves_spots_an_inserted_item():
    old = [(1, "Read the spec"), (2, "Run the checks"), (3, "Ask first")]
    new = [(1, "Read the spec"), (2, "A new rule"), (3, "Run the checks"), (4, "Ask first")]
    assert refs.moves(old, new) == {2: 3, 3: 4}


def test_moves_keeps_an_item_edited_in_place():
    old = [(1, "Read the spec"), (2, "Run the checks"), (3, "Ask first")]
    new = [(1, "Read the spec"), (2, "Run every check, and tflint"), (3, "Ask first")]
    assert refs.moves(old, new) == {}


def test_moves_spots_a_removed_item():
    old = [(1, "Read the spec"), (2, "Run the checks"), (3, "Ask first")]
    new = [(1, "Read the spec"), (2, "Ask first")]
    assert refs.moves(old, new) == {2: None, 3: 2}


@needs_git
def test_changed_lines_marks_edits_and_treats_new_files_as_new(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
):
    def git(*args: str) -> None:
        identity = ["-c", "user.name=t", "-c", "user.email=t@t"]
        subprocess.run(["git", *identity, *args], cwd=tmp_path, check=True)

    git("init", "-q")
    (tmp_path / "f.md").write_text("one\ntwo\nthree\n", encoding="utf-8")
    git("add", "f.md")
    git("commit", "-qm", "first")
    (tmp_path / "f.md").write_text("one\nTWO\nthree\n", encoding="utf-8")
    monkeypatch.setattr(refs, "ROOT", tmp_path)

    assert refs.changed_lines("HEAD", "f.md", {"f.md"}) == {2}
    assert refs.changed_lines("HEAD", "new.md", {"f.md"}) is None


