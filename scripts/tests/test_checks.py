def test_repo_references_are_valid():
    assert refs.main(None) == 0


def test_attribution_catches_ai_trailers_and_footers():
    text = (
        "Add tflint\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n"
        "Generated with [Claude Code](https://claude.com/claude-code)\n"
        "Generated by Copilot\n🤖 done"
    )
    assert len(attribution.problems(text)) == 4


def test_attribution_catches_markdown_footers():
    text = (
        "Summary\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n"
        "> Co-authored-by: Copilot"
    )
    assert len(attribution.problems(text)) == 2


def test_attribution_allows_a_sentence_quoting_the_rule():
    text = "Fails on a 'Generated with Claude Code' footer or an AI Co-authored-by line."
    assert attribution.problems(text) == []


def test_attribution_allows_human_co_authors_and_comments():
    text = "Add tflint\n\nCo-authored-by: Sam Lee <sam@example.com>\n# Generated with Claude"
    assert attribution.problems(text) == []
